ARTICLE_RE = re.compile(r"(?<![\w\-/])(?:the|an|a)(?![\w\-/])\s*", re.IGNORECASE)

PHRASE_RE = re.compile(
    r"(?<![\w\-/])(?:" + "|".join(re.escape(k) for k in sorted(PHRASES, key=len, reverse=True)) + r")(?![\w\-/])",
    re.IGNORECASE,
)
WORD_RE = re.compile(
    r"(?<![\w\-/])(" + "|".join(re.escape(k) for k in sorted(WORDS, key=len, reverse=True)) + r")(?![\w\-/])",
    re.IGNORECASE,
)


def translate(description: str) -> str:
    text = description.strip()
    if not text:
        return "客户端未提供描述"
    key = text.lower()
    if key in REVIEWED:
        return REVIEWED[key]
    if key in EXACT:
        return EXACT[key]

    text = ARTICLE_RE.sub(" ", text)

    # Protect inline command examples (`...`) from the glossary.
    protected = []

    def mask(match):
        protected.append(match.group(0))
        return f"@@{len(protected) - 1}@@"

    result = re.sub(r"`[^`]*`", mask, text)
    result = PHRASE_RE.sub(lambda m: PHRASES[m.group(0).lower()], result)
    result = WORD_RE.sub(lambda m: WORDS[m.group(0).lower()], result)
    for index, value in enumerate(protected):
        result = result.replace(f"@@{index}@@", value)
    result = re.sub(r"'s\b", "的", result)
    result = re.sub(r"\s+", " ", result).strip()
    result = re.sub(r"(?<=[\u4e00-\u9fff])\s+(?=[\u4e00-\u9fff])", "", result)
    result = re.sub(r"\s+([,.;:!?])", r"\1", result)
    if result.endswith("."):
        result = result[:-1] + "。"
    elif result.endswith("!"):
        result = result[:-1] + "！"
    elif result.endswith("?"):
        result = result[:-1] + "？"
    # If the glossary could not translate anything, keep the English text
    # rather than emitting a half-broken pseudo-translation.
    if not re.search(r"[\u4e00-\u9fff]", result):
        return text
    return result


def escape(value: str) -> str:
    return (value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;"))


def catalog_context(commands, language: str) -> str:
    lines = ["    <context>", "        <name>CommandCatalog</name>"]
    for row in commands:
        source = row["id"]
        if language == "zh_CN":
            translation = translate(row.get("description", ""))
        else:
            translation = row.get("description", "").strip() or "No description provided"
        lines.append("        <message>")
        lines.append(f"            <source>{escape(source)}</source>")
        lines.append(f"            <translation>{escape(translation)}</translation>")
        lines.append("        </message>")
    lines.append("    </context>")
    return "\n".join(lines)


