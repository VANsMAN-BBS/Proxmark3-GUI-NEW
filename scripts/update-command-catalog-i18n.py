def add_missing_messages(text: str, context: str, source: str, translation: str,
                         language: str) -> str:
    marker = f"<name>{context}</name>"
    marker_pos = text.find(marker)
    if marker_pos < 0:
        # New context (e.g. CommandCatalogModel).
        if language == "zh_CN":
            block = (f"    <context>\n        <name>{context}</name>\n"
                     f"        <message>\n            <source>{escape(source)}</source>\n"
                     f"            <translation>{escape(translation)}</translation>\n"
                     f"        </message>\n    </context>\n")
        else:
            block = (f"<context>\n    <name>{context}</name>\n"
                     f"    <message>\n        <source>{escape(source)}</source>\n"
                     f"        <translation type=\"unfinished\"></translation>\n"
                     f"    </message>\n</context>\n")
        return text.replace("</TS>", block + "</TS>")
    start = text.rfind("<context>", 0, marker_pos)
    if start < 0:
        raise SystemExit(f"context not found: {context}")
    end = text.find("</context>", start)
    block = text[start:end]
    if f"<source>{escape(source)}</source>" in block:
        return text
    if language == "zh_CN":
        body = (f"        <message>\n            <source>{escape(source)}</source>\n"
                f"            <translation>{escape(translation)}</translation>\n"
                f"        </message>\n    ")
    else:
        body = (f"    <message>\n        <source>{escape(source)}</source>\n"
                f"        <translation type=\"unfinished\"></translation>\n"
                f"    </message>\n")
    # Insert before the context closing tag.
    return text[:end] + body + text[end:]


def main() -> int:
    catalog_path = ROOT / "resources" / "commands" / "commands.json"
    data = json.loads(catalog_path.read_text(encoding="utf-8"))
    commands = data["commands"]

    for language in ("zh_CN", "en_US"):
        path = ROOT / "i18n" / f"{language}.ts"
        text = path.read_text(encoding="utf-8")
        # Replace an older generated catalog context.
        pattern = re.compile(
            r"\s*<context>\s*<name>CommandCatalog</name>.*?</context>", re.DOTALL)
        text = pattern.sub("", text)
        text = text.replace("\n</TS>", "\n" + catalog_context(commands, language) + "\n</TS>")
        for context, messages in UI_MESSAGES.items():
            for source, translation in messages.items():
                text = add_missing_messages(text, context, source, translation, language)
        path.write_text(text, encoding="utf-8")
        print(f"updated {path}")

    return 0


